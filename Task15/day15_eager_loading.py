# ------------------------------------------------------------
# Импорты стандартной библиотеки
# ------------------------------------------------------------
import os                       # читаем переменные окружения
from decimal import Decimal     # тип для денег (цена книги)
from pathlib import Path        # удобная работа с путями к файлам


# ------------------------------------------------------------
# Импорты сторонних библиотек
# ------------------------------------------------------------
from dotenv import load_dotenv  # читает .env и грузит переменные в окружение
from sqlalchemy import (
    String,         # тип колонки: строка с ограничением длины
    Integer,        # тип колонки: целое число
    Numeric,        # тип колонки: десятичное число с фиксированной точностью
    ForeignKey,     # описание внешнего ключа
    create_engine,  # создаёт движок подключения к базе
    select,         # функция для построения SQL-запроса (стиль 2.0)
)
from sqlalchemy.orm import (
    Mapped,          # аннотация типа для колонок и связей
    mapped_column,   # описывает колонку в таблице
    DeclarativeBase, # базовый класс для всех моделей
    Session,         # сессия — единица работы с базой
    relationship,    # описывает связь между моделями
)


# ------------------------------------------------------------
# Чтение DATABASE_URL из .env
# ------------------------------------------------------------
# Файл .env лежит в корне проекта — на два уровня выше этого файла.
# Path(__file__)          — путь к текущему файлу
# .resolve()              — делает путь абсолютным
# .parent                 — папка Task15
# .parent                 — корень MyPythonProjects
# / ".env"                — добавляет имя файла
env_path = Path(__file__).resolve().parent.parent / ".env"


# load_dotenv читает файл по указанному пути и подгружает переменные
# в окружение процесса. Если файла нет — просто ничего не делает.
load_dotenv(env_path)

# os.getenv возвращает значение переменной или None, если её нет.
# Мы проверяем явно, чтобы получить понятную ошибку вместо загадочной
# «None is not a valid URL» где-то дальше в create_engine.
DATABASE_URL = os.getenv("DTABASE_URL")
if DATABASE_URL is None:
    raise RuntimeError(
        f"DATABASE_URL не найден. Проверь, что файл {env_path} существует "
        f"и содержит строку DATABASE_URL=..."
    )


# ------------------------------------------------------------
# Движок подключения к базе
# ------------------------------------------------------------
# create_engine — создаёт объект Engine. Это не соединение с базой,
# а фабрика соединений: Engine умеет держать пул и выдавать сессии.
#
# echo=True — печатает ВСЕ SQL-запросы в консоль.
# Это главный инструмент Дня 15: без него мы не увидим, сколько
# запросов реально уходит в базу.
engine = create_engine(DATABASE_URL, echo=True)


# ------------------------------------------------------------
# Базовый класс для моделей
# ------------------------------------------------------------
# DeclarativeBase — базовый класс SQLAlchemy 2.0. Через него
# SQLAlchemy собирает метаданные: какие таблицы, колонки, связи.
# От него наследуются Author и Book.
class Base(DeclarativeBase):
    pass


# ------------------------------------------------------------
# Модель Author — таблица authors
# ------------------------------------------------------------
class Author(Base):
    __tablename__ = "authors"   # реальное имя таблицы в PostgreSQL

    # id — первичный ключ, целое число, NOT NULL
    id: Mapped[int] = mapped_column(primary_key=True)

    # name — строка до 100 символов, NOT NULL
    name: Mapped[str] = mapped_column(String(100))

    # country — строка до 50 символов, МОЖЕТ быть NULL
    # (поэтому в аннотации "str | None")
    country: Mapped[str | None] = mapped_column(String(50))

    # books — это НЕ колонка в базе. Это виртуальное свойство Python.
    # relationship говорит SQLAlchemy: "у одного автора много книг".
    # back_populates="author" — обратная сторона это Book.author.
    # Строка "Book" в кавычках — forward reference: класс Book
    # определён ниже, Python не может разрешить имя прямо сейчас.
    books: Mapped[list["Book"]] = relationship(back_populates="author")


    # ------------------------------------------------------------
    # Модель Book — таблица books
    # ------------------------------------------------------------
    class Book(Base):
        __tablename__ = "books"

        id: Mapped[int] = mapped_column(primary_key=True)
        title: Mapped[str] = mapped_column(String(200))     # до 200 символов
        year: Mapped[int | None] = mapped_column(Integer)   # может быть NULL

        # price — NUMERIC(10, 2): всего 10 цифр, из них 2 после запятой.
        # В Python это Decimal — точный тип для денег без потери копеек.
        price: Mapped[Decimal] = mapped_column(Numeric(10, 2))

        # author_id — внешний ключ на authors.id. Может быть NULL:
        # в данных есть книги без автора ("Анонимная рукопись").
        author_id : Mapped[int | None] = mapped_column(ForeignKey("authors.id"))

        # author — обратная сторона связи Author.books.
        # Тип "Author | None": у книги может не быть автора.
        author: Mapped["Author | None"] = relationship(back_populates="books")


# ============================================================
# ШАГ 1. Воспроизводим N+1
# ============================================================
# Здесь мы НЕ используем никаких options — значит, работает
# ленивая загрузка (lazy loading). Книги грузятся в тот момент,
# когда мы обращаемся к a.books.
#
# Что ожидаем увидеть в логе:
#   1 запрос   — SELECT FROM authors (получить всех авторов)
#   5 запросов — SELECT FROM books WHERE author_id = X
#                (по одному на каждого автора)
#   Итого: 6 запросов вместо одного логического действия.
# ============================================================

print("\n=== ШАГ 1: N+1 (ленивая загрузка) ===\n")

# with Session(engine) as session — открывает сессию и гарантирует
# её закрытие в конце блока, даже если внутри произойдёт ошибка.
with Session(engine) as session:
    # select(Author) — строим запрос "дай всех авторов".
    stmt = select(Author)

    # session.execute(stmt) — отправляет запрос в базу.
    # .scalars()            — говорит "в каждой строке одно значение".
    # .all()                — собирает все строки в список.
    authors = session.execute(stmt).scalars().all()