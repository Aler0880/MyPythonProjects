        col_widths = []
        for i in range(len(column_names)):
            max_len = len(column_names[i])
            for row in str_rows:
                if len(row[i]) > max_len:
                    max_len = len(row[i])
            col_widths.append(max_len)

        # Вывод заголовка
        header = " | ".join(
            col_name.ljust(col_widths[i]) for i, col_name in enumerate(column_names)
        )
