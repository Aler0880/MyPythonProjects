
"""
Программа для работы с облачной базой данных Neon (PostgreSQL).
Выполняет создание таблицы, вставку, обновление, удаление и выборку книг.
Использует утилиту psql для выполнения SQL-команд — это надёжнее драйверов.
"""

# Импортируем модуль для запуска внешних программ (psql)
import subprocess

# Импортируем для работы с системой (проверка файлов, пути)
import os

# Импортируем для создания временных файлов
import tempfile

# --------------------------------------------------------------------
# 1. ПУТЬ К ИСПОЛНЯЕМОМУ ФАЙЛУ PSQL
# --------------------------------------------------------------------
# Укажи путь к psql.exe на своём компьютере.
# Версия PostgreSQL может отличаться (17, 16 и т.д.) — измени цифру.
PSQL_PATH = r"C:\Program Files\PostgreSQL\18\bin\psql.exe"


# --------------------------------------------------------------------
# 2. СТРОКА ПОДКЛЮЧЕНИЯ К NEON
# --------------------------------------------------------------------
# Это строка, которую мы скопировали из консоли Neon.
# Она содержит: пользователя, пароль, хост (без -pooler), базу данных.
# sslmode=require — обязательный параметр для защищённого соединения.
DATABASE_URL = (
    "postgresql://neondb_owner:npg_T6JB4QhCdoGX@ep-small-hat-axiiwy73.c-4.us-east-2.aws.neon.tech/neondb"
    "?sslmode=require"
)


# --------------------------------------------------------------------
# 3. СПИСОК SQL-КОМАНД (каждая команда — отдельная строка)
# --------------------------------------------------------------------
# Команды разбиты так, чтобы каждая выполнялась в своём соединении.
# Это предотвращает разрыв соединения при длительных транзакциях.
commands = [
    # Команда 1: создаём таблицу, если её нет.
    "CREATE TABLE IF NOT EXISTS books ("
    "id SERIAL PRIMARY KEY,"
    "title VARCHAR(255) NOT NULL,"
    "author VARCHAR(255) NOT NULL,"
    "year INTEGER,"
    "pages INTEGER,"
    "message TEXT"
    ");",
    # Команда 2: очищаем таблицу и сбрасываем счётчик id.
    # Это нужно, чтобы при каждом запуске данные не дублировались.
    "TRUNCATE TABLE books RESTART IDENTITY;",
    # Команда 3: вставляем три книги одной командой.
    # Используем VALUES с несколькими кортежами — это быстрее.
    "INSERT INTO books (title, author, year, pages, message) VALUES "
    "('Название книги 1', 'Автор 1', 2020, 350, 'Краткое описание'), "
    "('Название книги 2', 'Автор 2', 2018, 420, 'Другое описание'), "
    "('Название книги 3', 'Автор 3', 2021, 280, 'Ещё одно описание');",
    # Команда 4: добавляем четвёртую книгу отдельно.
    "INSERT INTO books (title, author, year, pages, message) VALUES "
    "('1984', 'George Orwell', 1949, 328, 'Роман-антиутопия');",
    # Команда 5: выводим все книги после вставки.
    # SELECT с псевдонимом info создаёт красивый заголовок.
    "SELECT '=== Список всех книг (после добавления) ===' AS info;"
    " SELECT * FROM books ORDER BY id;",
    # Команда 6: обновляем год у книги с id=1 и выводим сообщение.
    "UPDATE books SET year = 2025 WHERE id = 1;"
    " SELECT '=== Год книги с id=1 обновлён на 2025 ===' AS info;",
    # Команда 7: удаляем книгу с id=2 и выводим сообщение.
    "DELETE FROM books WHERE id = 2;" " SELECT '=== Книга с id=2 удалена ===' AS info;",
    # Команда 8: финальный вывод всех книг после изменений.
    "SELECT '=== Итоговый список книг (после обновления и удаления) ===' AS info;"
    " SELECT * FROM books ORDER BY id;",
]


# --------------------------------------------------------------------
# 4. ФУНКЦИЯ ДЛЯ ВЫПОЛНЕНИЯ ОДНОЙ КОМАНДЫ ЧЕРЕЗ PSQL
# --------------------------------------------------------------------
def run_psql_command(sql):
    """
    Принимает строку SQL, сохраняет её во временный файл в кодировке UTF-8,
    затем выполняет этот файл через psql -f.
    Возвращает True, если команда выполнилась без ошибок, иначе False.
    """
    # ----------------------------------------------------------------
    # 1. СОЗДАЁМ ВРЕМЕННЫЙ SQL-ФАЙЛ С КОДИРОВКОЙ UTF-8
    # ----------------------------------------------------------------
    # mode='w' — открываем для записи (текст)
    # suffix='.sql' — расширение файла
    # delete=False — файл не будет удалён автоматически (удалим в finally)
    # encoding='utf-8' — явно задаём кодировку, чтобы кириллица передалась корректно
    with tempfile.NamedTemporaryFile(
        mode="w",
        suffix=".sql",
        delete=False,
        encoding="utf-8"
    ) as f:
        f.write(sql)          # записываем команду в файл
        sql_file = f.name     # запоминаем полный путь к файлу

    try:
        # ----------------------------------------------------------------
        # 2. ФОРМИРУЕМ КОМАНДУ ДЛЯ ЗАПУСКА psql
        # ----------------------------------------------------------------
        # [0] путь к исполняемому файлу psql
        # -d  строка_подключения
        # -f  имя_файла  — выполнить содержимое файла
        # --no-psqlrc   — игнорировать системные и пользовательские настройки psql
        # -q            — тихий режим (минимум лишнего вывода)
        cmd = [
            PSQL_PATH,
            "-d", DATABASE_URL,
            "-f", sql_file,
            "--no-psqlrc",
            "-q"
        ]

        # ----------------------------------------------------------------
        # 3. НАСТРАИВАЕМ ПЕРЕМЕННЫЕ ОКРУЖЕНИЯ
        # ----------------------------------------------------------------
        # Копируем текущее окружение, чтобы не потерять системные пути.
        env = os.environ.copy()

        # Устанавливаем кодировку клиента — это говорит psql, в какой кодировке
        # отправлять данные на сервер (обязательно UTF-8 для кириллицы).
        env["PGCLIENTENCODING"] = "UTF8"

        # Устанавливаем язык сообщений psql на английский.
        # Без этой настройки psql выводит сообщения на русском в кодировке,
        # которая не совпадает с консолью Windows, и появляются ромбики с вопросиками.
        # "C" — это нейтральная локаль, все сообщения будут на английском.
        env["LC_MESSAGES"] = "C"

        # ----------------------------------------------------------------
        # 4. ЗАПУСКАЕМ ПРОЦЕСС psql И ЗАХВАТЫВАЕМ ВЫВОД
        # ----------------------------------------------------------------
        # capture_output=True — перехватываем stdout и stderr
        # text=True           — возвращаем вывод как строку (не байты)
        # encoding='utf-8'    — декодируем вывод в UTF-8 (чтобы правильно отображать данные)
        # errors='replace'    — если встретится байт, который нельзя декодировать,
        #                       заменяем его на символ � (чтобы не было исключения)
        # env=env             — передаём наше окружение с переменными
        result = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            env=env,
        )

        # ----------------------------------------------------------------
        # 5. АНАЛИЗ РЕЗУЛЬТАТА ВЫПОЛНЕНИЯ
        # ----------------------------------------------------------------
        if result.returncode != 0:
            # Код возврата не 0 — произошла ошибка
            print(f"❌ Ошибка в команде:\n{sql}\n")
            print(f"STDERR: {result.stderr}")
            return False
        else:
            # Всё хорошо. Если stdout не пустой, печатаем его.
            # (обычно там содержатся результаты SELECT'ов или сообщения об успехе)
            if result.stdout.strip():
                print(result.stdout)
            return True

    except Exception as e:
        # Перехватываем любые исключения (например, файл не найден, нет прав и т.п.)
        print(f"❌ Исключение: {e}")
        return False
    finally:
        # ----------------------------------------------------------------
        # 6. УДАЛЯЕМ ВРЕМЕННЫЙ ФАЙЛ
        # ----------------------------------------------------------------
        # Это делается независимо от того, была ошибка или нет.
        # Проверяем, что файл существует, чтобы не вызвать ошибку при удалении.
        if os.path.exists(sql_file):
            os.remove(sql_file)


# --------------------------------------------------------------------
# 5. ОСНОВНАЯ ПРОГРАММА
# --------------------------------------------------------------------
if __name__ == "__main__":
    # Выводим стартовое сообщение.
    print("🚀 Запуск команд по очереди через временные файлы...\n")

    # Переменная для отслеживания успеха.
    success = True

    # Перебираем все SQL-команды по порядку.
    for i, sql in enumerate(commands, 1):
        # Номер команды для наглядности.
        print(f"--- Команда {i} ---")
        # Выполняем команду. Если вернулся False — прерываем цикл.
        if not run_psql_command(sql):
            success = False
            break

    # Итоговое сообщение.
    if success:
        print("\n✅ Все команды выполнены успешно!")
    else:
        print("\n❌ Ошибка на одной из команд.")
